std::vector<uint8_t> font_atlas() {
    std::vector<uint8_t> px((size_t)FONT_ATLAS_W * FONT_ATLAS_H * 4, 0);
    for (const Glyph& g : GLYPHS) {
        int code = (unsigned char)g.c - 32;
        if (code < 0 || code >= FONT_COLS * FONT_ROWS) continue;
        int ox = (code % FONT_COLS) * FONT_CELL, oy = (code / FONT_COLS) * FONT_CELL;
        for (int y = 0; y < 7; y++)
            for (int x = 0; x < 5; x++) {
                if (g.rows[y][x] != '#') continue;
                uint8_t* p = &px[((size_t)(oy + y) * FONT_ATLAS_W + ox + x) * 4];
                p[0] = p[1] = p[2] = p[3] = 255;
            }
    }
    return px;
}

